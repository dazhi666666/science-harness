/* Mission Control 语言层：中文是源文本与默认语言；English 由 EN 词典按源文本翻译。
 * 中文界面里的技术名词（Run、Agent、Provider、Artifact…）保持英文，由 ZH 词典覆盖源文本。 */
const KEY = 'mission-control-lang'

export const lang = (() => {
  try { return localStorage.getItem(KEY) === 'en' ? 'en' : 'zh' } catch { return 'zh' }
})()
export const locale = lang === 'en' ? 'en-US' : 'zh-CN'

export function setLang(next) {
  try { localStorage.setItem(KEY, next) } catch {}
  location.reload()
}

/** Translate a Chinese source string; `{name}` placeholders are filled from vars. */
export function t(key, vars) {
  let s = (lang === 'en' ? EN : ZH)[key] ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
  return s
}

/** Static markup: `data-i18n` translates text (key = original Chinese text), `data-i18n-attr="placeholder,title"` translates attributes. */
export function applyStatic(root = document) {
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN'
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.dataset.i18n ||= el.textContent.trim()
    el.textContent = t(el.dataset.i18n)
  }
  for (const el of root.querySelectorAll('[data-i18n-attr]'))
    for (const attr of el.dataset.i18nAttr.split(',')) {
      const k = 'i18nSrc' + attr.replace(/-./g, (m) => m[1].toUpperCase()).replace(/^./, (c) => c.toUpperCase())
      el.dataset[k] ||= el.getAttribute(attr) ?? ''
      el.setAttribute(attr, t(el.dataset[k]))
    }
}

